#!/usr/bin/env python3
"""Builds assets/data/world_sample.json from Natural Earth 1:110m countries.

Writes every country with its ISO codes, English/Spanish names, flag emoji,
label centroid and polygon rings ('areas'). Run from the repo root:
  python3 tool/build_country_shapes.py
"""
import json
import re

CONTENT = "assets/data/world_sample.json"
NE = "tool/natural_earth/ne_110m_admin_0_countries.geojson"


def flag_emoji(iso2: str) -> str:
    return "".join(chr(0x1F1E6 + ord(c) - ord("A")) for c in iso2.upper())


def main():
    countries = []
    for f in json.load(open(NE))["features"]:
        p, g = f["properties"], f["geometry"]
        code = p["ADM0_A3"]
        iso2 = (p.get("ISO_A2_EH") or p.get("ISO_A2") or "").strip()
        if code == "ATA" or len(iso2) != 2 or not iso2.isalpha():
            continue
        polys = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
        rings = [
            [[round(lo, 3), round(la, 3)] for lo, la in ring]
            for poly in polys
            for ring in poly
        ]
        name_en = p.get("NAME_EN") or p["NAME"]
        name_es = p.get("NAME_ES") or name_en
        countries.append(
            {
                "code": code,
                "iso2": iso2.lower(),
                "name": name_en,
                "name_es": name_es,
                "flag": flag_emoji(iso2),
                "centroid": {
                    "lat": round(p["LABEL_Y"], 4),
                    "lon": round(p["LABEL_X"], 4),
                },
                "areas": rings,
            }
        )

    countries.sort(key=lambda c: c["code"])
    data = {
        "about": "Natural Earth 1:110m countries ('areas' are rings in GeoJSON [lon, lat] order, generated by tool/build_country_shapes.py).",
        "countries": countries,
    }
    text = json.dumps(data, ensure_ascii=False, indent=2)
    text = re.sub(r"\[\s+(-?[\d.]+),\s+(-?[\d.]+)\s+\]", r"[\1, \2]", text)
    text = re.sub(
        r"(\[-?[\d.]+, -?[\d.]+\]),\s+(?=\[-?[\d.]+, -?[\d.]+\])", r"\1, ", text
    )
    open(CONTENT, "w").write(text + "\n")
    print(f"Wrote {len(countries)} countries to {CONTENT}")


if __name__ == "__main__":
    main()
